    // Metodo para construir una lista con los id de los niños
    private String nombresNinos(List<Nino> ninos) {
        if (ninos == null || ninos.isEmpty()) {
            return "-";
        }
        return ninos.stream()
                .map(Nino::getNombre)
                .collect(Collectors.joining(", "));
    }

    /**
     * Construye un String con los identificadores de una lista de Demogorgons
     * separados por coma. Ejemplo: "D0000, D0003". Devuelve "-" si está vacía.
     */
    private String nombresDemos(List<Demogorgon> demos) {
        if (demos == null || demos.isEmpty()) {
            return "-";
        }
        return demos.stream()
                .map(Demogorgon::getNombre)
                .collect(Collectors.joining(", "));
    }

    /**
     * Traduce el tipo de evento a texto legible en español.
     */
    private String nombreEvento(TipoEvento tipo) {
        switch (tipo) {
            case APAGON_LABORATORIO:
                return "Apagon Laboratorio";
            case TORMENTA_UPSIDE_DOWN:
                return "Tormenta Upside Down";
            case INTERVENCION_ELEVEN:
                return "Intervencion Eleven";
            case RED_MENTAL:
                return "La Red Mental";
            default:
                return tipo.name();
        }
    }

    /**
     * Actualiza el campo de estado de un portal con texto y color según su
     * situación actual.
     */
    private void actualizarEstadoPortal(javax.swing.JTextField campo, Portal portal) {
        if (portal.isApagado()) {
            campo.setText("APAGADO");
            campo.setForeground(java.awt.Color.RED);
        } else {
            // Obtenemos el nombre del niño que está dentro del portal en este mismo
            // instante
            String ninoCruzando = portal.getNombreNinoCruzando();

            if (ninoCruzando != null && !ninoCruzando.isEmpty()) {
                // Hay un niño cruzando el tunel
                campo.setText(ninoCruzando);
                campo.setForeground(Color.BLUE);

            } else {
                // El tunel esta vacio
                campo.setText("Libre");
                campo.setForeground(Color.BLACK);
            }
        }
    }

    /**
     * Refresca todos los campos de la interfaz con los datos actuales del
     * modelo. Se llama automáticamente cada 500 ms por el Timer.
     */
    private void actualizarUI() {
        if (callePrincipal == null) {
            return; // sin modelo (modo diseño)
        }
        // ── Hawkins ───────────────────────────────────────────────────────────
        txtCalleNinos.setText(nombresNinos(callePrincipal.getNinos()));
        txtSotanoNinos.setText(nombresNinos(sotanoByers.getNinos()));
        txtRadioNinos.setText(nombresNinos(radioWSQK.getNinos()));

        // PORTAL 0: BOSQUE
        try {
            txtPortalBosqueHwks.setText(nombresNinos(portales[0].getEsperandoGrupo()));
            actualizarEstadoPortal(txtPortalBosqueCruzando, portales[0]);
            txtPortalBosqueUD.setText(nombresNinos(portales[0].getEsperandoRegreso()));
        } catch (Exception e) {
            System.err.println("Error UI Bosque: " + e.getMessage());
        }

        // PORTAL 1: LABORATORIO
        try {
            txtPortalLabHwks.setText(nombresNinos(portales[1].getEsperandoGrupo()));
            actualizarEstadoPortal(txtPortalLabCruzando, portales[1]);
            txtPortalLabUD.setText(nombresNinos(portales[1].getEsperandoRegreso()));
        } catch (Exception e) {
            System.err.println("Error UI Laboratorio: " + e.getMessage());
        }

        // PORTAL 2: CENTRO COMERCIAL
        try {
            txtPortalCCHawkins.setText(nombresNinos(portales[2].getEsperandoGrupo()));
            actualizarEstadoPortal(txtPortalCCCruzando, portales[2]);
            txtPortalCCUD.setText(nombresNinos(portales[2].getEsperandoRegreso()));
        } catch (Exception e) {
            System.err.println("Error UI C.Comercial: " + e.getMessage());
        }

        // PORTAL 3: ALCANTARILLADO
        try {
            txtPortalAlcHawkins.setText(nombresNinos(portales[3].getEsperandoGrupo()));
            actualizarEstadoPortal(txtPortalAlcantarilladoCruzando, portales[3]);
            txtPortalAlcantarilladoUD.setText(nombresNinos(portales[3].getEsperandoRegreso()));
        } catch (Exception e) {
            System.err.println("Error UI Alcantarillado: " + e.getMessage());
        }

        // Upside Down
        txtBosqueNinos.setText(nombresNinos(bosque.getNinos()));
        txtBosqueDemos.setText(nombresDemos(bosque.getDemogorgons()));

        txtLabNinos.setText(nombresNinos(laboratorio.getNinos()));
        txtLabDemos.setText(nombresDemos(laboratorio.getDemogorgons()));

        txtCCNinos.setText(nombresNinos(centroComercial.getNinos()));
        txtCCDemos.setText(nombresDemos(centroComercial.getDemogorgons()));

        txtAlcNinos.setText(nombresNinos(alcantarillado.getNinos()));
        txtAlcDemos.setText(nombresDemos(alcantarillado.getDemogorgons()));

        // Colmena
        txtColmenaActual.setText(nombresNinos(colmena.getNinosCapturados()));
        txtColmenaTotal.setText(String.valueOf(colmena.getTotalCapturas()));

        // Sangre de Vecna
        txtSangre.setText(String.valueOf(gestorEventos.getSangreRecolectada()));

        // Evento global
        TipoEvento evento = gestorEventos.getEventoActivo();
        if (evento == null) {
            txtEventoTipo.setText("Sin evento activo");
            txtEventoTiempo.setText("-");
        } else {
            txtEventoTipo.setText(nombreEvento(evento));
            long restante = gestorEventos.getTiempoRestante();
            txtEventoTiempo.setText(restante > 0 ? restante + " s" : "-");
        }
    }

