    private void btnPausarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnPausarActionPerformed
        if (servidor == null)
            return;

        try {
            boolean estabaPausado = servidor.estaSimulacionPausada();
            if (estabaPausado) {
                servidor.reanudarSimulacion();
            } else {
                servidor.pausarSimulacion();
            }

            // Actualizamos la variable local y el texto del botón
            pausado = !estabaPausado;
            btnPausar.setText(pausado ? "Reanudar" : "Pausar");

        } catch (Exception e) {
            System.err.println("Error RMI al intentar pausar/reanudar: " + e.getMessage());
        }
    }// GEN-LAST:event_btnPausarActionPerformed

    private void iniciarActualizacionAutomatica() {
        // Ejecuta la actualización cada 500 ms (medio segundo)
        Timer timer = new Timer(500, new java.awt.event.ActionListener() {
            @Override
            public void actionPerformed(java.awt.event.ActionEvent e) {
                actualizarDatos();
            }
        });
        timer.start();
    }

    private void actualizarDatos() {
        if (servidor == null) {
            return; // Si no hay conexión RMI, no hacemos nada
        }

        // 1. NIÑOS EN HAWKINS
        try {
            int ninosHawkins = servidor.getNinosHawkins();
            txtTotalHawkins.setText(String.valueOf(ninosHawkins));
        } catch (Exception e) {
            txtTotalHawkins.setText("Err");
            System.err.println("Error RMI obteniendo niños en Hawkins: " + e.getMessage());
        }

        // 2. ESTADO DE PORTALES
        try {
            int[] ninosPortales = servidor.getNinosPortales();
            if (ninosPortales != null && ninosPortales.length >= 4) {
                txtPortalBosque.setText(String.valueOf(ninosPortales[0]));
                txtPortalLaboratorio.setText(String.valueOf(ninosPortales[1]));
                txtPortalCentroComercial.setText(String.valueOf(ninosPortales[2]));
                txtPortalAlcantarillado.setText(String.valueOf(ninosPortales[3]));
            }
        } catch (Exception e) {
            txtPortalBosque.setText("Err");
            txtPortalLaboratorio.setText("Err");
            txtPortalCentroComercial.setText("Err");
            txtPortalAlcantarillado.setText("Err");
            System.err.println("Error RMI obteniendo portales: " + e.getMessage());
        }

        // 3. NIÑOS EN EL UPSIDE DOWN Y COLMENA
        try {
            int[] ninosUD = servidor.getNinosUpsideDown();
            if (ninosUD != null && ninosUD.length >= 4) {
                txtNinosBosque.setText(String.valueOf(ninosUD[0]));
                txtNinosLaboratorio.setText(String.valueOf(ninosUD[1]));
                txtNinosCentroComercial.setText(String.valueOf(ninosUD[2]));
                txtNinosAlcantarillado.setText(String.valueOf(ninosUD[3]));
            }

            // La colmena tiene su propio método en tu interfaz
            int ninosColmena = servidor.getNinosCapturadosEnColmena();
            txtNinosColmena.setText(String.valueOf(ninosColmena));

        } catch (Exception e) {
            txtNinosBosque.setText("Err");
            txtNinosLaboratorio.setText("Err");
            txtNinosCentroComercial.setText("Err");
            txtNinosAlcantarillado.setText("Err");
            txtNinosColmena.setText("Err");
            System.err.println("Error RMI obteniendo niños en Upside Down: " + e.getMessage());
        }

        // 4. DEMOGORGONS EN EL UPSIDE DOWN
        try {
            int[] demosUD = servidor.getDemogorgonsUpsideDown();
            if (demosUD != null && demosUD.length >= 4) {
                txtDemosBosque.setText(String.valueOf(demosUD[0]));
                txtDemosLaboratorio.setText(String.valueOf(demosUD[1]));
                txtDemosCentroCompercial.setText(String.valueOf(demosUD[2]));
                txtDemosAlcantarillado.setText(String.valueOf(demosUD[3]));
            }
        } catch (Exception e) {
            txtDemosBosque.setText("Err");
            txtDemosLaboratorio.setText("Err");
            txtDemosCentroCompercial.setText("Err");
            txtDemosAlcantarillado.setText("Err");
            System.err.println("Error RMI obteniendo demogorgons: " + e.getMessage());
        }

        // 5. RANKING DE DEMOGORGONS
        try {
            List<String> ranking = servidor.getRankingDemogorgons();
            // Llenamos las 3 cajas comprobando si la lista tiene suficientes elementos
            txtRanking1.setText(ranking != null && ranking.size() > 0 ? ranking.get(0) : "");
            txtRanking2.setText(ranking != null && ranking.size() > 1 ? ranking.get(1) : "");
            txtRanking3.setText(ranking != null && ranking.size() > 2 ? ranking.get(2) : "");
        } catch (Exception e) {
            txtRanking1.setText("Err");
            txtRanking2.setText("");
            txtRanking3.setText("");
            System.err.println("Error RMI obteniendo ranking: " + e.getMessage());
        }

        // 6. EVENTO GLOBAL ACTIVO
        try {
            String evento = servidor.getEventoActivo();
            txtEventoTipo.setText(evento);

            // Si hay un evento activo, pedimos el tiempo restante
            if (!evento.equals("Sin evento activo")) {
                long tiempo = servidor.getTiempoRestanteEvento();
                txtEventoTiempo.setText(tiempo + " segs");
            } else {
                txtEventoTiempo.setText("--");
            }
        } catch (Exception e) {
            txtEventoTipo.setText("Err");
            txtEventoTiempo.setText("Err");
            System.err.println("Error RMI obteniendo evento: " + e.getMessage());
        }
    }

